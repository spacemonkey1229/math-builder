#!/usr/bin/env python3
"""
Sensitivity model — Cinema.

Contract (skills/case-readiness, Tier 2 Probe 5):
    PARAMS   dict[str, number]   every dial the case STATES (given or assumed)
    FLEX     list[str]           the subset that is a genuine stated ASSUMPTION
    def evaluate(params) -> {"A": metric, "B": metric}     higher is better
    def evaluate_twist(params) -> {"A": metric, "B": metric}

Primary metric: opening-weekend (Thu-Sun) net profit (ticket revenue + concession
revenue - per-showing exhibition cost) generated by The Revengers and Lizzie And
The Last Unicorn TOGETHER, comparing:

  Option A "The Unicorn House" — Lizzie gets the 150-seat theater exclusively;
      The Revengers runs its required daily minimum only in 85-seat theaters.
  Option B "The Revengers House" — The Revengers gets the 150-seat theater
      exclusively; Lizzie runs its required daily minimum only in 85-seat theaters.

Per case.md Appendix D (Modeling Assumptions): each of Appendix B's five named
attendance windows is treated as one candidate daily showtime slot per movie/
theater (D-1); a movie assigned N required daily showings (N=5 Revengers, N=4
Lizzie) fills all 5 slots if N>=5, or the N most-profitable of the 5 slots if
N<5 (D-5 — run at contractual minimum, never fewer, never gratuitously more).
Ticket price is matinee ($7.75) before 4pm, standard ($11.50) at/after 4pm
(D-2). Attendance-capacity percent is uniform across movies (D-3). Concession
revenue per ticket uses the midpoint of each spending band, with the open-
ended top band ("more than $40") assumed at $50 (D-4) -- the ONE genuinely
author-estimated number in this model; everything else in PARAMS is Appendix
A/B given data, not an assumption, and is therefore NOT in FLEX (see doctrine
note in skills/case-readiness/SKILL.md: only genuine stated assumptions are
swept by Tier 2 probe 5, never cited/given data).

Verified against cases/cinema/case.json's derived{} block:
    base   A (Unicorn House)   = $66,764.08
           B (Revengers House) = $68,673.05
           margin  ~2.86%, B wins
"""

# ---- five named attendance windows, Appendix B ----------------------------
SLOTS_BY_DAY = {
    "Thu": [15, 35, 45, 70, 55],   # Monday-Thursday profile
    "Fri": [20, 55, 80, 95, 75],
    "Sat": [45, 65, 90, 97, 85],   # Saturday-Sunday profile
    "Sun": [45, 65, 90, 97, 85],
}
# window 1-2 = matinee (before 4pm), window 3-5 = standard (at/after 4pm)
PRICE_BY_WINDOW = ["matinee", "matinee", "standard", "standard", "standard"]

PARAMS = {
    # --- Appendix B: Tickets ------------------------------------------------
    "matinee_price": 7.75,
    "standard_price": 11.50,
    # --- Appendix C: theater sizes ------------------------------------------
    "large_seats": 150,
    "small_seats": 85,
    # --- Appendix A: the two major releases ----------------------------------
    "revengers_cost_per_showing": 220.00,
    "revengers_min_daily_showings": 5,
    "lizzie_cost_per_showing": 325.00,
    "lizzie_min_daily_showings": 4,
    # --- Appendix B: Concessions (D-4) --------------------------------------
    "concession_high_band_midpoint": 37.50,   # $30-45 band, 5% of ticket holders
    "concession_mid_band_midpoint": 21.00,    # $12-30 band, 51% of ticket holders
    "concession_low_band_midpoint": 8.00,     # $4-12 band,  27% of ticket holders
    "concession_top_band_share": 0.02,        # >$40 band,   2% of ticket holders
    "concession_high_band_share": 0.05,
    "concession_mid_band_share": 0.51,
    "concession_low_band_share": 0.27,
    "concession_zero_band_share": 0.15,
    # --- THE ONE GENUINE ASSUMPTION (Appendix D, D-4) -----------------------
    # The ">$40" band has no stated upper bound. This is an author estimate,
    # not a cited figure -- the only entry in FLEX.
    "concession_top_band_estimate": 50.00,
}

# Only a genuine, author-stated ASSUMPTION belongs here (SPEC sec.2 / house
# doctrine) -- never cited/given data. Every other PARAMS entry above is a
# number Appendix A, B, or C states outright.
FLEX = [
    "concession_top_band_estimate",
]


def _expected_concession_per_ticket(params):
    p = params
    return (
        p["concession_top_band_share"] * p["concession_top_band_estimate"]
        + p["concession_high_band_share"] * p["concession_high_band_midpoint"]
        + p["concession_mid_band_share"] * p["concession_mid_band_midpoint"]
        + p["concession_low_band_share"] * p["concession_low_band_midpoint"]
        + p["concession_zero_band_share"] * 0.0
    )


def _slot_revenue(seats, cap_pct, window_idx, params, econ_per_ticket):
    price = params["matinee_price"] if PRICE_BY_WINDOW[window_idx] == "matinee" else params["standard_price"]
    tickets = seats * (cap_pct / 100.0)
    return tickets * (price + econ_per_ticket)


def _movie_weekend_net_profit(seats, cost_per_showing, min_daily, params, econ_per_ticket):
    total = 0.0
    for day, caps in SLOTS_BY_DAY.items():
        revs = [_slot_revenue(seats, caps[i], i, params, econ_per_ticket) for i in range(5)]
        if min_daily >= 5:
            chosen = revs
        else:
            drop_n = 5 - min_daily
            drop_idx = set(sorted(range(5), key=lambda i: revs[i])[:drop_n])
            chosen = [revs[i] for i in range(5) if i not in drop_idx]
        day_revenue = sum(chosen)
        day_cost = cost_per_showing * len(chosen)
        total += day_revenue - day_cost
    return total


def evaluate(params):
    """{"A": Unicorn House net profit, "B": Revengers House net profit}."""
    econ = _expected_concession_per_ticket(params)
    revengers_large = _movie_weekend_net_profit(
        params["large_seats"], params["revengers_cost_per_showing"],
        params["revengers_min_daily_showings"], params, econ)
    revengers_small = _movie_weekend_net_profit(
        params["small_seats"], params["revengers_cost_per_showing"],
        params["revengers_min_daily_showings"], params, econ)
    lizzie_large = _movie_weekend_net_profit(
        params["large_seats"], params["lizzie_cost_per_showing"],
        params["lizzie_min_daily_showings"], params, econ)
    lizzie_small = _movie_weekend_net_profit(
        params["small_seats"], params["lizzie_cost_per_showing"],
        params["lizzie_min_daily_showings"], params, econ)
    option_a = lizzie_large + revengers_small     # The Unicorn House
    option_b = revengers_large + lizzie_small     # The Revengers House
    return {"A": round(option_a, 2), "B": round(option_b, 2)}


def evaluate_twist(params):
    """
    The Twist (FACILITATOR.md): a distributor addendum reveals a per-showing
    "flagship placement" marketing co-op fee of $50, owed on every small-
    theater (85-seat) showing of WHICHEVER major release is NOT given the
    large theater -- waived entirely for the release placed in the large
    theater, which already satisfies the distributor's premium-placement
    clause. This does not touch any given Appendix A/B figure; it is new
    information revealed mid-discussion, applied on top of the same base
    arithmetic.
    """
    base = evaluate(params)
    fee_per_confined_showing = 50.00
    revengers_confined_showings = params["revengers_min_daily_showings"] * 4  # 4 weekend days
    lizzie_confined_showings = params["lizzie_min_daily_showings"] * 4
    option_a = base["A"] - fee_per_confined_showing * revengers_confined_showings   # Revengers confined
    option_b = base["B"] - fee_per_confined_showing * lizzie_confined_showings      # Lizzie confined
    return {"A": round(option_a, 2), "B": round(option_b, 2)}


if __name__ == "__main__":
    base = evaluate(PARAMS)
    twist = evaluate_twist(PARAMS)
    print("BASE:", base, "winner:", max(base, key=base.get),
          f"margin {100*(max(base.values())-min(base.values()))/min(base.values()):.2f}%")
    print("TWIST:", twist, "winner:", max(twist, key=twist.get),
          f"margin {100*(max(twist.values())-min(twist.values()))/min(twist.values()):.2f}%")
